const fs = require('fs');
const path = require('path');
const https = require('https');

// 从 constants.ts 中获取厂商配置
function getProvidersFromConstants() {
  const constantsPath = path.join(__dirname, '../app/constant.ts');
  const constantsContent = fs.readFileSync(constantsPath, 'utf8');
  
  // 提取 ServiceProvider 配置中的厂商 ID
  const providerIds = [];
  
  // 匹配 ServiceProvider 对象中的每个厂商配置
  const serviceProviderMatch = constantsContent.match(/export const ServiceProvider[^}]+= \{([\s\S]*?)\n\};/);
  
  if (serviceProviderMatch) {
    const serviceProviderContent = serviceProviderMatch[1];
    
    // 匹配每个厂商的 id 字段
    const idMatches = serviceProviderContent.match(/id:\s*"([^"]+)"/g);
    
    if (idMatches) {
      idMatches.forEach(match => {
        const id = match.match(/id:\s*"([^"]+)"/)[1];
        providerIds.push(id);
      });
    }
  }
  
  console.log('Found provider IDs:', providerIds);
  return providerIds;
}

// 下载文件的辅助函数
function downloadFile(url, dest) {
  return new Promise((resolve, reject) => {
    const file = fs.createWriteStream(dest);
    
    https.get(url, (response) => {
      if (response.statusCode === 200) {
        response.pipe(file);
        file.on('finish', () => {
          file.close();
          resolve();
        });
      } else if (response.statusCode === 302 || response.statusCode === 301) {
        // 处理重定向
        downloadFile(response.headers.location, dest).then(resolve).catch(reject);
      } else {
        reject(new Error(`Failed to download ${url}: ${response.statusCode}`));
      }
    }).on('error', (err) => {
      fs.unlink(dest, () => {}); // 删除部分下载的文件
      reject(err);
    });
  });
}

// 获取 JSON 数据的辅助函数
function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (response) => {
      let data = '';
      
      response.on('data', (chunk) => {
        data += chunk;
      });
      
      response.on('end', () => {
        try {
          const json = JSON.parse(data);
          resolve(json);
        } catch (error) {
          reject(error);
        }
      });
    }).on('error', (err) => {
      reject(err);
    });
  });
}

// 下载厂商图标
async function downloadProviderLogos(providerIds) {
  const logosDir = path.join(__dirname, '../public/logos');
  
  // 确保目录存在
  if (!fs.existsSync(logosDir)) {
    fs.mkdirSync(logosDir, { recursive: true });
  }
  
  console.log('Downloading provider logos...');
  
  for (const providerId of providerIds) {
    try {
      const logoUrl = `https://models.dev/logos/${providerId}.svg`;
      const logoPath = path.join(logosDir, `${providerId}.svg`);
      
      await downloadFile(logoUrl, logoPath);
      console.log(`✓ Downloaded logo for ${providerId}`);
    } catch (error) {
      console.warn(`⚠ Failed to download logo for ${providerId}:`, error.message);
    }
  }
}

// 获取模型配置
async function fetchModelsConfig() {
  console.log('Fetching models configuration from models.dev...');
  
  try {
    const config = await fetchJson('https://models.dev/api.json');
    return config;
  } catch (error) {
    console.error('Failed to fetch models config:', error);
    return null;
  }
}

// 生成模型配置文件
function generateModelsConfig(modelsConfig, providerIds) {
  const configDir = path.join(__dirname, '../app/config/generated');
  
  // 确保目录存在
  if (!fs.existsSync(configDir)) {
    fs.mkdirSync(configDir, { recursive: true });
  }
  
  // 提取我们需要的厂商配置
  const filteredConfig = {};
  
  providerIds.forEach(providerId => {
    if (modelsConfig[providerId]) {
      filteredConfig[providerId] = modelsConfig[providerId];
    }
  });
  
  console.log(`✓ Filtered configuration for ${Object.keys(filteredConfig).length} providers`);
  
  // 直接保存原始 JSON 结构
  const configContent = `// 此文件由构建脚本自动生成，请勿手动修改
// Generated by scripts/fetch-models-config.js from models.dev/api.json

export const MODELS_DEV_CONFIG = ${JSON.stringify(filteredConfig, null, 2)} as const;
`;
  
  const configPath = path.join(configDir, 'models-config.ts');
  fs.writeFileSync(configPath, configContent);
  
  console.log('✓ Generated models configuration file with original structure');
  
  // 返回统计信息
  const stats = {
    providersCount: Object.keys(filteredConfig).length,
    modelsCount: Object.values(filteredConfig).reduce((total, provider) => {
      return total + (provider.models ? Object.keys(provider.models).length : 0);
    }, 0),
    filteredConfig,
  };
  
  return stats;
}

// 主函数
async function main() {
  try {
    console.log('🚀 Starting models configuration fetch...');
    
    // 1. 获取厂商列表
    const providerIds = getProvidersFromConstants();
    
    // 2. 下载厂商图标
    await downloadProviderLogos(providerIds);
    
    // 3. 获取模型配置
    const modelsConfig = await fetchModelsConfig();
    
    if (modelsConfig) {
      // 4. 生成配置文件
      const stats = generateModelsConfig(modelsConfig, providerIds);
      
      console.log('✅ Successfully generated models configuration!');
      console.log(`🏭 Generated configuration for ${stats.providersCount} providers`);
      console.log(`📝 Generated configuration for ${stats.modelsCount} models`);
    } else {
      console.error('❌ Failed to fetch models configuration');
      process.exit(1);
    }
    
  } catch (error) {
    console.error('❌ Error:', error);
    process.exit(1);
  }
}

// 运行脚本
if (require.main === module) {
  main();
}

module.exports = { main };